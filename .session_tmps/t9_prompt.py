import io

p = "backend/app/agent/prompts.py"
t = io.open(p, encoding="utf-8").read()

old = '''要求：
1. 来自证据的句子，末尾标注证据编号，例如 [E1]；只能使用证据里出现的编号。
2. 证据不足的部分可以用你的专业知识补充，但补充的句子不要标注任何编号，并在补充内容前用一句话说明「以下为一般知识，非知识库内容」。
3. 带编号的句子里，数字必须与证据原文一致；需要推算时写在不带编号的句子里，并写出推算过程。
4. 涉及医疗、法律、投资等风险话题时，提醒信息仅供参考，重要决策请咨询专业人士。
5. 用简洁的中文作答，条理清楚时使用列表。'''

new = '''要求：
1. 来自证据的句子，末尾标注证据编号，例如 [E1]；只能使用证据里出现的编号。
2. 证据不足的部分可以用你的专业知识补充，但补充的句子不要标注任何编号，并在补充内容前用一句话说明「以下为一般知识，非知识库内容」。
3. 如果证据与问题无关，不要描述、复述或引用这些证据。第一句直接写「知识库中暂无相关资料，以下回答基于一般知识，仅供参考。」，然后用一般知识回答，不标任何编号。
4. 说明「知识库没有某项信息」的句子要单独成句，不标编号。
5. 带编号的句子里，数字必须与证据原文一致；需要推算时写在不带编号的句子里，并写出推算过程。
6. 涉及医疗、法律、投资等风险话题时，提醒信息仅供参考，重要决策请咨询专业人士。
7. 用简洁的中文作答，条理清楚时使用列表。'''

assert old in t, "REFERENCE_ANSWER_PROMPT requirements not found"
t = t.replace(old, new, 1)
io.open(p, "w", encoding="utf-8", newline="").write(t)
print("prompts.py updated")

